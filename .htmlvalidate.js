// Проверка разметки лендинга и деки.
//
//   npm run check:html
//
// html-validate (github.com/html-validate/html-validate, MIT) читает HTML и
// ловит то, что браузер молча проглотит: незакрытые теги, атрибуты не на
// своих элементах, устаревшие конструкции.
//
// Что нашла первая же проверка: aria-label на голом div. Скринридер его не
// читает — подпись относится к роли, а роли у div нет. Карточка «Пример
// объявления» на первом экране была для незрячего просто пустым местом.
// Починено добавлением role="group".
//
// Конфигурация в .js, а не в .json, ровно ради этих строк: json-конфиг
// html-validate лишних полей не принимает, и объяснить в нём решения
// негде.
module.exports = {
  extends: ['html-validate:recommended'],

  rules: {
    // Правило требует выносить все style="…" в таблицу стилей. У нас таких
    // мест 74, и почти все — точечный отступ у одного блока. Переписать их
    // в классы значит завести 74 класса с одним свойством каждый: список
    // исключений переедет из разметки в CSS, но не исчезнет.
    'no-inline-style': 'off',

    // Про пробелы в конце строк исходника. К тому, что видит человек,
    // отношения не имеет.
    'no-trailing-whitespace': 'off',
  },

  elements: ['html5'],
};
