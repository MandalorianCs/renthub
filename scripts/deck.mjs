// Отпечаток деки: из какого текста напечатан PDF.
//
// Отдельный модуль, а не функция внутри pitch-pdf.mjs. Первая попытка
// импортировала её оттуда — и `npm run check:pitch` начинал ПЕЧАТАТЬ
// деку: в том файле код лежит на верхнем уровне, и импорт исполняет его
// целиком. Проверка, запускающая браузер ради одного хеша, — это уже не
// проверка.

import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Отпечаток деки, из которой напечатан PDF.
 *
 * Переводы строк нормализуются, и это не косметика. Git на Windows держит
 * в рабочем дереве CRLF, а в репозитории LF: хеш файла «как есть» на
 * машине и в CI получается РАЗНЫЙ, и проверка свежести падала на каждом
 * прогоне CI независимо от того, свежий PDF или нет. Ровно вторая версия
 * той же ошибки — первая сравнивала время файлов, которого git не хранит
 * вовсе.
 *
 * Считается от содержания, а не от байтов: свежесть означает «напечатано
 * из этого текста», а перевод строки текста не меняет.
 */
export function deckFingerprint(root) {
  const text = readFileSync(join(root, 'landing', 'pitch.html'), 'utf8').replace(/\r\n/g, '\n');
  return createHash('sha256').update(text, 'utf8').digest('hex');
}
