// Выход из скрипта, который не притворяется падением.
//
// `process.exit()` обрывает процесс немедленно, не давая закрыться тому,
// что ещё открыто. Клиент supabase-js держит соединение, и на Windows это
// кончается падением libuv:
//
//   Assertion failed: !(handle->flags & UV_HANDLE_CLOSING), win\async.c
//
// Код выхода при этом становится **127** — «команда не найдена». Измерено
// 05.09.2026 на трёх вариантах:
//
//   node без supabase, process.exit(0)   → 0
//   supabase + process.exit(0)           → 127
//   supabase + process.exitCode = 0      → 0
//
// Цена оказалась не косметической. `npm run check` соединяет проверки через
// `&&`, и цепочка обрывалась на первой же: скрипт печатал зелёный отчёт и
// сообщал системе, что упал. То же самое сделал бы CI, если бы эти команды
// туда попали.
//
// `process.exitCode` задаёт код, но даёт процессу закончиться самому —
// когда закроются соединения и опустеет очередь событий.

/**
 * Закончить работу с заданным кодом.
 *
 * Возвращает `true`, чтобы вызывающий мог написать `if (done(1)) return;` —
 * `process.exitCode` не прерывает выполнение, и остановиться надо явно.
 */
export function done(code = 0) {
  process.exitCode = code;
  return true;
}
