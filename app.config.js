// Тонкая надстройка над app.json — ровно одно поле.
//
// Зачем. Веб-сборка вшивает `experiments.baseUrl` в бандл: по нему
// приложение находит свои же файлы. Пока адрес был один (/renthub/app),
// хватало строки в app.json.
//
// С 06.09.2026 оформлений три, и живут они по разным адресам — /app,
// /app2, /app3. Без переопределения вторая и третья версии тянули бы
// бандл первой: страница открылась бы, а оформление показала чужое.
// Причём молча — файлы-то нашлись.
//
// Всё остальное берётся из app.json без изменений. Отдельного файла
// конфигурации с копией настроек здесь нет намеренно: копия разошлась
// бы с оригиналом, а Expo умеет накладывать одно на другое сам.
//
// EAS читает эту же надстройку. Для сборки APK переменная не задаётся, и
// baseUrl остаётся тем, что записан в app.json, — нативной сборке он всё
// равно не нужен, но пусть будет тем же, что был.

const base = require('./app.json');

module.exports = ({ config }) => ({
  ...config,
  experiments: {
    ...config.experiments,
    baseUrl: process.env.EXPO_BASE_URL ?? base.expo.experiments.baseUrl,
  },
});
