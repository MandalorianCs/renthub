import { Platform } from 'react-native';

/**
 * Оформление выбирается переменной EXPO_PUBLIC_THEME.
 *
 * Вариантов три, и все они — ОДИН бренд. Палитра из деки не меняется:
 * кремовый фон, приглушённая терракота, тёмно-зелёный для «всё в
 * порядке». DESIGN.md на этом настаивает прямо — «не заменять бренд
 * готовым UI-китом», — и запрет остаётся в силе.
 *
 * Меняется пластика: сколько воздуха между блоками, насколько круглые
 * карточки, есть ли под ними тень. Это то, что человек замечает раньше
 * цвета и о чём говорит «выглядит дороже» или «выглядит проще», не умея
 * объяснить, что именно увидел.
 *
 *   warm  (по умолчанию)  то, что было: мягкие тени, средние скругления
 *   calm                  больше воздуха, крупнее скругления, тени почти
 *                         нет — граница вместо неё
 *   sharp                 плотнее и контрастнее: тонкие рамки, малые
 *                         скругления
 *
 * Размеры шрифта варианты НЕ меняют, хотя раньше здесь лежала заготовка
 * для этого. Она ни к чему не была подключена: экраны берут начертание из
 * typeface и ставят кегль сами. Заготовка, о которой знает только
 * комментарий, — это обещание, а не поведение; удалена вместе с ним.
 *
 * Собираются они в разные адреса — /app, /app2, /app3, — чтобы их можно
 * было открыть рядом и сравнить, а не помнить, как было вчера.
 */
const VARIANT = (process.env.EXPO_PUBLIC_THEME ?? 'warm') as 'warm' | 'calm' | 'sharp';


export const colors = {
  bg: '#FAF7F2',
  surface: '#FFFFFF',

  // Граница в sharp заметнее: там она несёт то, что в остальных
  // вариантах делает тень. Плоский интерфейс без границ читается как
  // недорисованный, а не как минималистичный.
  border: VARIANT === 'sharp' ? '#D8CEC0' : VARIANT === 'calm' ? '#EDE7DE' : '#E7E0D6',
  text: '#1A1917',
  textMuted: '#6E675E',
  accent: '#C2603C', // терракота — основное действие
  accentSoft: '#F6E7E0',
  green: '#2F5D50', // подтверждено / деньги начислены
  greenSoft: '#E3EDE9',
  // Янтарный затемнён с #B8860B до #8C6508: на своей подложке прежний
  // давал 2,81 : 1 — вдвое ниже нормы. Пометки «ожидание» и «срок
  // подходит» стоят на самых важных экранах сделки, и читать их иногда
  // приходится на солнце, с телефона, во дворе. Стало 4,56 : 1.
  warn: '#8C6508', // ожидание, срок подходит
  warnSoft: '#F6EEDA',
  danger: '#A33A2A', // спор, просрочка
  dangerSoft: '#F7E3DF',

  /**
   * Белый на плотной заливке — терракоте, зелёном, красном, чернильном.
   *
   * Это роль, а не цвет. Записанный по месту `#FFFFFF` неотличим от
   * `surface`, хотя означает противоположное: там это фон карточки, здесь —
   * текст поверх фона. Разведены, чтобы правка одного не задевала второе.
   */
  onFill: '#FFFFFF',

  /**
   * Белый поверх затемнения — счётчик фото на снимке, просмотрщик.
   *
   * Отдельно от `onFill` потому, что подложка здесь чужая: под ней
   * фотография, а не наш цвет. В тёмной теме `onFill` может поменяться,
   * а этот — нет, снимок останется снимком.
   */
  onScrim: '#FFFFFF',
} as const;

/**
 * Отступы. В calm их больше на четверть — это и есть «воздух», из-за
 * которого один и тот же экран выглядит спокойнее; в sharp меньше на
 * восьмую, чтобы на экран помещалось больше карточек.
 *
 * Числа, а не множитель по месту: множитель пришлось бы помнить в каждом
 * файле, а забытый однажды даёт экран, собранный из двух ритмов.
 */
export const spacing =
  VARIANT === 'calm'
    ? ({ xs: 5, sm: 10, md: 15, lg: 20, xl: 30, xxl: 40 } as const)
    : VARIANT === 'sharp'
      ? ({ xs: 4, sm: 7, md: 11, lg: 14, xl: 21, xxl: 28 } as const)
      : ({ xs: 4, sm: 8, md: 12, lg: 16, xl: 24, xxl: 32 } as const);

/**
 * Тень задаётся токеном, а не по месту: карточка объявления и карточка сделки
 * должны лежать на одной высоте, иначе интерфейс выглядит собранным из кусков.
 *
 * Платформ теперь три, а не две. `shadow*` — язык iOS, `elevation` — Android,
 * а react-native-web раньше переводил `shadow*` в `box-shadow` сам, но объявил
 * это устаревшим и пишет предупреждение в консоль на каждый экран. Поэтому
 * вебу отдаётся готовый `boxShadow`, остальным — прежние наборы.
 *
 * Значения подобраны так, чтобы совпадать визуально: 0 6px 16px при
 * непрозрачности 6% — это ровно то, что react-native-web собирал из
 * shadowOffset, shadowRadius и shadowOpacity.
 */
const native = {
  card: {
    shadowColor: '#1A1917',
    shadowOffset: { width: 0, height: 6 },
    shadowOpacity: 0.06,
    shadowRadius: 16,
    elevation: 2,
  },
  raised: {
    shadowColor: '#1A1917',
    shadowOffset: { width: 0, height: 10 },
    shadowOpacity: 0.14,
    shadowRadius: 22,
    elevation: 6,
  },
};

const web = {
  card: { boxShadow: '0 6px 16px rgba(26, 25, 23, 0.06)' },
  raised: { boxShadow: '0 10px 22px rgba(26, 25, 23, 0.14)' },
};

/**
 * Тени по вариантам.
 *
 * В calm карточка почти не отрывается от фона: тень едва заметна, а
 * «предмет» держится скруглением и воздухом вокруг. В sharp тени нет
 * вовсе — её работу делает граница, и это осознанный выбор, а не
 * упрощение: DESIGN.md говорит, что плоская рамка сообщает «это
 * область», а тень — «это объект». В sharp мы говорим первое.
 */
const flat = { card: {}, raised: {} };

const soft =
  Platform.OS === 'web'
    ? {
        card: { boxShadow: '0 4px 14px rgba(26, 25, 23, 0.04)' },
        raised: { boxShadow: '0 8px 20px rgba(26, 25, 23, 0.09)' },
      }
    : {
        card: {
          shadowColor: '#1A1917',
          shadowOffset: { width: 0, height: 4 },
          shadowOpacity: 0.04,
          shadowRadius: 14,
          elevation: 1,
        },
        raised: {
          shadowColor: '#1A1917',
          shadowOffset: { width: 0, height: 8 },
          shadowOpacity: 0.09,
          shadowRadius: 20,
          elevation: 4,
        },
      };

export const elevation =
  VARIANT === 'sharp' ? flat : VARIANT === 'calm' ? soft : Platform.OS === 'web' ? web : native;

// xl — для карточек, которые человек воспринимает как предмет: витрина
// каталога, карточка объявления. Мелкое скругление на большой плоскости
// читается как прямоугольник со срезанными углами, а не как объект.
export const radius =
  VARIANT === 'calm'
    ? ({ sm: 12, md: 18, lg: 24, xl: 32, pill: 999 } as const)
    : VARIANT === 'sharp'
      ? ({ sm: 4, md: 6, lg: 10, xl: 12, pill: 999 } as const)
      : ({ sm: 8, md: 12, lg: 16, xl: 22, pill: 999 } as const);

/**
 * Начертания Manrope — тот же шрифт, что на лендинге, чтобы сайт и
 * приложение читались как один продукт.
 *
 * Важно: со своим шрифтом `fontWeight` работать перестаёт. На Android он
 * просто игнорируется, на iOS и в вебе рисуется синтетическая жирность —
 * кривая и разная на разных платформах. Поэтому вес выбирается именем
 * файла, а не числом: fontFamily: typeface[700] вместо fontWeight: '700'.
 */
export const typeface = {
  400: 'Manrope_400Regular',
  500: 'Manrope_500Medium',
  600: 'Manrope_600SemiBold',
  700: 'Manrope_700Bold',
  800: 'Manrope_800ExtraBold',
} as const;

