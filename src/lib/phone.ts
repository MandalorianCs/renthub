/**
 * Правила телефона: нормализация номера и внутренний адрес учётной записи.
 *
 * Почему отдельный файл. Эти две функции нужны трём входам сразу:
 * приложению (экран входа), скрипту приглашения (scripts/invite.mjs) и
 * боту (bot/bot.py). Раньше они жили внутри src/lib/auth.tsx, а скрипт
 * держал свою копию — с комментарием «правило обязано совпадать»,
 * который совпадение не обеспечивает, а только напоминает о нём.
 *
 * Теперь у JavaScript-мира копия одна: auth.tsx и invite.mjs читают этот
 * файл. Он намеренно без React и без Supabase — иначе скрипт, которому
 * нужна одна строчная функция, потянул бы за собой половину приложения.
 *
 * У бота копия остаётся: он на Python, и разделить код с ним нельзя.
 * Зато совпадение проверяется командой — npm run check:bot прогоняет обе
 * реализации на одних номерах и сверяет ответы.
 */

/**
 * Казахстанские номера: 8 705… и +7 705… — это один и тот же номер.
 *
 * Человек набирает так, как привык, а база хранит один вид: иначе один
 * и тот же номер заводит два аккаунта, и владелец не находит своё
 * объявление.
 */
export function normalizePhone(input: string): string {
  const digits = input.replace(/\D/g, '');
  if (digits.startsWith('8') && digits.length === 11) return `+7${digits.slice(1)}`;
  if (digits.startsWith('7') && digits.length === 11) return `+${digits}`;
  return `+${digits}`;
}

/**
 * Телефон → внутренний адрес учётной записи.
 *
 * Человек этого адреса не видит и не вводит: на экране входа он набирает
 * номер, а клиент собирает адрес по этому правилу. Скрипт приглашения
 * заводит аккаунт с ним же — разойдутся, и человек с верным паролем не
 * сможет войти, а причину будут искать в пароле.
 */
export function inviteEmail(phone: string): string {
  return `${phone.replace(/\D/g, '')}@renthub.test`;
}
