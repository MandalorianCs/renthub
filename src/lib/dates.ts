/**
 * Даты сделки — сутками, а не мгновениями.
 *
 * ── Зачем отдельный модуль ───────────────────────────────────
 *
 * В базе `start_date` и `end_date` — это `date`, календарные сутки без
 * времени и без пояса. «С 10 по 13 сентября» значит одно и то же в
 * Кокшетау и в Нью-Йорке: четверо суток, названные числами.
 *
 * JavaScript думает иначе, и молча. `new Date('2026-09-10')` по стандарту
 * разбирается как ПОЛНОЧЬ UTC, а `getDate()`, `toLocaleDateString()` и
 * всё остальное читают её в МЕСТНОМ поясе. Для пояса западнее Гринвича
 * полночь UTC — это ещё вчера, и дата съезжает на сутки: аренда «с 10-го»
 * показывается как «с 9-го», а календарь гасит не тот день.
 *
 * Обратная ошибка того же рода — `new Date().toISOString().slice(0, 10)`.
 * Это UTC-сегодня, а не местное сегодня. В Кокшетау (UTC+5) с полуночи до
 * пяти утра оно возвращает ВЧЕРАШНЕЕ число: кнопка «на 3 дня» подставляла
 * дату, которую календарь тут же красил как прошедшую, а база отвергала
 * с RENTHUB_PAST_DATE. Человек, открывший приложение ночью, не делал
 * ничего неправильного — и получал отказ.
 *
 * ── Почему модуль пустой от оформления ───────────────────────
 *
 * Здесь нет ни одного импорта: ни темы, ни React Native. Это позволяет
 * запустить эти функции обычным `node` — и `npm run check:dates` их
 * запускает, каждую в шести часовых поясах сразу. Правило, которое можно
 * проверить командой, лучше правила, записанного в комментарии; тот же
 * приём, что у `src/lib/phone.ts`.
 *
 * Форматирование (`formatDate` и родня) живёт здесь по той же причине:
 * оно тоже про сутки, и ошибается тем же способом.
 *
 * `formatDateTime` осталось в format.ts намеренно. Оно показывает СРОКИ —
 * «вернуть до 12 сентября, 21:00», — а срок приходит из базы отметкой
 * времени с поясом. Переводить её в местное время правильно, и обычный
 * `new Date()` там как раз то, что нужно.
 */

/** Дата без времени в ISO — единственный формат, которым оперируют сутки. */
export function toISO(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

/**
 * Разбор строки-даты без подмены суток.
 *
 * Для `YYYY-MM-DD` собираем дату местным конструктором: получается
 * полночь на месте, а не полночь в Гринвиче. Всё остальное — отметки
 * времени с поясом — отдаём стандартному разбору: там перевод в местное
 * время и есть верное поведение.
 */
export function parseDate(iso: string): Date {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
  if (!m) return new Date(iso);
  return new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3]));
}

/** Сегодня по часам человека, а не по Гринвичу. */
export function todayISO(): string {
  return toISO(new Date());
}

/** Сдвиг на сутки вперёд или назад, оставаясь в местных сутках. */
export function addDays(iso: string, days: number): string {
  const d = parseDate(iso);
  d.setDate(d.getDate() + days);
  return toISO(d);
}

/**
 * Все дни интервала, обе границы включительно.
 *
 * Включительно — потому что так считает база: аренда «с 1 по 1 число» это
 * одни сутки, а не ноль. Расхождение здесь означало бы, что календарь
 * гасит не те дни, что запрещает `bookings_no_overlap`.
 */
export function eachDay(fromISO: string, toISOStr: string): string[] {
  const out: string[] = [];
  const cursor = parseDate(fromISO);
  const last = parseDate(toISOStr);
  // Ограничение сверху — защита от порченых данных, а не от нормальной
  // аренды: год суток заведомо больше любого разумного интервала, а
  // бесконечный цикл в календаре повесил бы экран молча.
  while (cursor <= last && out.length < 366) {
    out.push(toISO(cursor));
    cursor.setDate(cursor.getDate() + 1);
  }
  return out;
}

/**
 * Дата человеческими словами: «10 сент.», «12 дек. 2025».
 *
 * Год появляется, только когда он не текущий. Без этого «12 дек.» в
 * истории сделок читается как декабрь этого года, хотя может быть
 * прошлогодним, — и чем старше аккаунт, тем чаще. Даты будущих броней от
 * добавки не страдают: они почти всегда в текущем году.
 *
 * Бот делает то же самое в human_date(), но словом целиком: «12 декабря».
 * Различие намеренное — в колонке экрана места меньше, чем в строке чата,
 * — и записано здесь, чтобы следующий читатель не «починил» его до
 * одинаковости.
 *
 * Вид даты не менялся при переносе сюда: `toLocaleDateString('ru-RU')`
 * остался тем же. Ошибка была в разборе строки, а не в оформлении, и
 * править заодно второе значило бы прятать первое.
 */
export function formatDate(iso: string): string {
  const d = parseDate(iso);
  const sameYear = d.getFullYear() === new Date().getFullYear();
  return sameYear ? formatDay(iso) : formatDayYear(iso);
}

/** День и месяц без года — левая половина диапазона внутри одного года. */
export function formatDay(iso: string): string {
  return parseDate(iso).toLocaleDateString('ru-RU', { day: 'numeric', month: 'short' });
}

/**
 * День, месяц и год — всегда. Для диапазонов через границу года.
 *
 * «12 дек. 2025 г.» — два лишних знака в колонке, где место на счету.
 * Год и так стоит числом, слово «г.» ничего к нему не добавляет.
 */
export function formatDayYear(iso: string): string {
  return parseDate(iso)
    .toLocaleDateString('ru-RU', { day: 'numeric', month: 'short', year: 'numeric' })
    .replace(' г.', '');
}

/**
 * Диапазон дат в самом коротком виде, который ещё не врёт.
 *
 * Повторять то, что уже сказано, — значит заставлять перечитывать.
 * «12 дек. 2025 — 15 дек. 2025» несёт ровно столько же, сколько
 * «12 — 15 дек. 2025», но занимает вдвое больше места в карточке, где
 * рядом стоят название, статус и сумма.
 *
 * Три вида, по убыванию частоты:
 *   один месяц      12 — 15 дек.
 *   один год        28 нояб. — 3 дек.
 *   разные годы     28 дек. 2025 — 3 янв. 2026
 */
export function formatDateRange(startISO: string, endISO: string): string {
  const from = parseDate(startISO);
  const to = parseDate(endISO);

  const sameYear = from.getFullYear() === to.getFullYear();
  const sameMonth = sameYear && from.getMonth() === to.getMonth();

  if (sameMonth) return `${from.getDate()} — ${formatDate(endISO)}`;
  if (sameYear) return `${formatDay(startISO)} — ${formatDate(endISO)}`;

  // Разные годы: год ставится у обеих дат, даже если правая в текущем.
  // «28 дек. 2025 — 3 янв.» заставляет достраивать год самому, а «3 янв.
  // 2026» не оставляет вопроса — за два лишних знака на редком случае.
  return `${formatDayYear(startISO)} — ${formatDayYear(endISO)}`;
}
