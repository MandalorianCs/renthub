import owner from '../../shared/demo-owner.json';

/**
 * Демонстрационные объявления витрины.
 *
 * Зачем это в приложении. На витрине пилота сейчас лежат только они — восемь
 * вещей от одного служебного владельца, заведённые `npm run demo:fill`, чтобы
 * продукт было что показать. Пока каталог смотрят свои, это нормально. Но
 * лендинг зовёт «открыть каталог», а страница для жюри — «откройте прямо
 * сейчас», и оба ведут ровно сюда.
 *
 * Что происходило дальше. Человек выбирал вещь и нажимал «Забронировать».
 * Бронь уходила в `pending` и оставалась там навсегда: подтверждать её
 * некому — у объявления нет живого владельца. Через срок аренды её молча
 * закрывал планировщик. Технически всё срабатывало правильно, а человек
 * делал единственно возможный вывод: платформа мёртвая.
 *
 * Почему пометка, а не удаление. Пустая витрина отвечает на вопрос «а есть
 * ли тут вообще перфоратор» словом «нет» — и это худший ответ, чем
 * «вот как это выглядит». Пометка сохраняет показ и убирает обман: видно
 * заранее, что вещь демонстрационная, и не приходится узнавать это тишиной
 * в ответ на заявку.
 *
 * Имя владельца лежит в `shared/demo-owner.json` — его же читает
 * `scripts/demo-listings.mjs`, который эти объявления заводит и чистит.
 * Признак «демо» принадлежит владельцу, а не вещи: удаление идёт по
 * владельцу, и второй признак пришлось бы держать в согласии с первым.
 */
export const DEMO_OWNER_NAME = owner.fullName;

export function isDemoOwner(fullName: string | null | undefined): boolean {
  return (fullName ?? '').trim() === DEMO_OWNER_NAME;
}

/** Одна строка объяснения — она же и на карточке, и на экране вещи. */
