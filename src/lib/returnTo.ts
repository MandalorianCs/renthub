/**
 * Куда вернуть человека после входа.
 *
 * Ссылку на сделку бот присылает в Telegram, и открывают её где угодно — в
 * том числе там, где не входили. Маршрутный сторож в app/_layout.tsx уводил
 * на экран входа, а после входа отправлял в каталог: адрес, по которому
 * человек пришёл, терялся, и сделку приходилось искать заново.
 *
 * Модульная переменная, а не состояние React: значение живёт между двумя
 * экранами и переживает их размонтирование. Хранилище браузера здесь не
 * нужно — перезагрузки между этими шагами не происходит, а на нативе его и
 * нет.
 */
let pending: string | null = null;

/** Запомнить адрес, на котором человека остановил вход. */
export function rememberRoute(path: string) {
  // Сам экран входа запоминать нельзя: после успеха он вернул бы на себя
  // же, и человек остался бы в петле.
  if (path.startsWith('/sign-in')) return;
  pending = path;
}

/**
 * Забрать запомненный адрес — ровно один раз.
 *
 * Одноразовость важна: иначе второй вход за сессию (например, после смены
 * аккаунта) увёл бы человека туда, куда он шёл когда-то давно.
 */
export function takeRoute(): string | null {
  const path = pending;
  pending = null;
  return path;
}
