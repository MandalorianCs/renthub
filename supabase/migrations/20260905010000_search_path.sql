-- Четыре функции без фиксированного search_path.
--
-- Нашёл встроенный аудит Supabase (`get_advisors`, тип security): четыре
-- функции помечены `function_search_path_mutable`. Остальные шестьдесят с
-- лишним предупреждений — про гранты anon и authenticated, и они ожидаемы:
-- функции сделок исполнимы анонимом по гранту, но отказывают изнутри через
-- assert_signed_in() (миграция 20260904110000). Аудит смотрит на грант, а
-- не на тело, и это разница между «может позвать» и «может сделать».
--
-- Насколько это серьёзно. Меньше, чем звучит: ни одна из четырёх НЕ
-- security definer — проверено запросом к pg_proc, prosecdef = false у
-- всех. Значит классическая атака «подменить объект в схеме, которая
-- ищется раньше, и выполнить свой код с правами владельца» здесь не
-- работает: функция выполняется с правами вызывающего, и подменять ему
-- нечего — своих схем у него нет, PostgREST их создавать не даёт.
--
-- Тогда зачем чинить. Потому что это стоит четыре строки, а свойство
-- «security definer» у функции меняется одним словом. Сегодня
-- decide_dispute_payout считает выплату по спору обычной функцией; в тот
-- день, когда ей понадобятся права владельца, никто не вспомнит, что
-- search_path у неё подвижный. Дешевле закрыть сейчас, чем помнить.
--
-- alter function, а не create or replace: меняется только предложение SET,
-- тело остаётся ровно тем, что уже проверено стендом. Переписывать сюда
-- сорок строк users_role_guard значило бы завести вторую копию правила
-- ради изменения, которое к правилу отношения не имеет.

alter function public.setting(text)
  set search_path = public;

alter function public.decide_dispute_payout(integer, integer)
  set search_path = public;

alter function public.users_role_guard()
  set search_path = public;

alter function public.assert_item_price(integer)
  set search_path = public;
