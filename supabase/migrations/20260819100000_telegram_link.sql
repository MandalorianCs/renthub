-- ─────────────────────────────────────────────────────────────
-- Привязка Telegram и закрытие личных колонок в users
--
-- Зачем привязка. SMS-провайдер для Казахстана стоит $250 в месяц только
-- за регистрацию имени отправителя. Telegram решает ту же задачу лучше и
-- бесплатно: при первом открытии бота человек нажимает «Поделиться
-- номером», и номер приходит подтверждённым самим Telegram — это сильнее
-- SMS-кода, который подтверждает лишь владение симкой в момент ввода.
--
-- Направление важно: бот не может написать первым. Telegram запрещает
-- боту слать сообщение тому, кто сам не начал диалог. Поэтому привязка
-- всегда начинается со стороны человека, а не приложения, и код входа
-- можно отправить только тому, у кого telegram_id уже записан.
-- ─────────────────────────────────────────────────────────────

alter table users add column telegram_id bigint unique;
alter table users add column telegram_username text;

comment on column users.telegram_id is
  'Чат с ботом. Заполняется ботом после «Поделиться номером»: только так '
  'Telegram отдаёт подтверждённый номер, и только после этого боту вообще '
  'разрешено писать этому человеку.';

-- Бот ищет получателя по номеру — индекс на phone уже есть (unique),
-- а этот нужен обратному направлению: входящее сообщение → пользователь.
create index users_telegram_idx on users (telegram_id) where telegram_id is not null;

-- ─────────────────────────────────────────────────────────────
-- Личные колонки: телефон и Telegram
--
-- Политика users_read разрешает любому вошедшему читать строки целиком.
-- Для анонима лишние колонки закрыты грантом (см. 20260816210000), а для
-- authenticated — нет, и телефон соседа доставался обычным запросом к API.
-- Ни один экран его не показывает, но API — это не экран.
--
-- Приложению это не мешает: свой профиль оно берёт функцией my_profile(),
-- а чужие карточки и так показывают только имя и рейтинг.
--
-- Порядок обязателен: сначала revoke, потом гранты поимённо. Без revoke
-- более широкое право, выданное дефолтными привилегиями проекта,
-- перекроет колоночное.
-- ─────────────────────────────────────────────────────────────

revoke select on users from authenticated;

-- is_moderator в списке не по недосмотру. Политики модератора устроены как
-- `exists (select 1 from users u where u.id = auth.uid() and u.is_moderator)`,
-- а политика выполняется с правами вызывающего. Закрой эту колонку — и
-- обычный арендатор теряет каталог целиком: Postgres проверяет все политики
-- на таблице, включая ту, что к нему не относится, и падает на отказе в
-- доступе. Стенд ловит это первым же сценарием.
--
-- Альтернатива — обернуть проверку в security definer функцию и переписать
-- четыре политики. Она чище, но и цена ошибки в ней выше: право «разбирать
-- споры» — не тайна, а вот телефон и Telegram — тайна, и они закрыты.
grant select (id, full_name, rating, ratings_count, created_at, is_moderator)
  on users to authenticated;

comment on column users.phone is
  'Виден только владельцу строки — через my_profile(). Прямым запросом к '
  'таблице недоступен ни анониму, ни другому участнику.';

-- ─────────────────────────────────────────────────────────────
-- Свой профиль целиком
--
-- security definer здесь не дыра, а сужение: функция физически не может
-- вернуть чужую строку — она читает ровно по auth.uid(). То же решение,
-- что у item_busy_dates(): вместо ослабления политики — узкая функция.
-- ─────────────────────────────────────────────────────────────

create or replace function my_profile()
returns users
language sql
stable
security definer
set search_path = public
as $$
  select * from users where id = auth.uid();
$$;

comment on function my_profile() is
  'Профиль вызывающего целиком, включая телефон и telegram_id. Единственный '
  'способ прочитать эти колонки из приложения.';

revoke all on function my_profile() from public;
grant execute on function my_profile() to authenticated;
