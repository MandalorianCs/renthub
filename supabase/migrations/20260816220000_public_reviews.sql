-- Отзывы видны и без входа.
--
-- Рейтинг без возможности прочитать отзывы — это цифра без объяснения,
-- ей не верят. Раз витрина открыта анониму, то и главный сигнал доверия
-- должен быть открыт: иначе человек видит «4,8» и не может проверить,
-- из чего она сложилась.
--
-- Раскрывать здесь нечего: в отзыве нет ни сумм, ни дат аренды, ни
-- телефонов. Имена авторов аноним и так видит — они выданы колоночным
-- грантом в предыдущей миграции.

create policy reviews_read_anon on reviews
  for select to anon
  using (true);
