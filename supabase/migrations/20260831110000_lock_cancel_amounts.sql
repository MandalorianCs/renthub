-- ─────────────────────────────────────────────────────────────
-- Прямая правка брони закрыта совсем
--
-- README с 28.08.2026 считает этот вопрос закрытым, и это было неверно.
-- Отмена действительно переехала в booking_cancel(), приложение и бот
-- ходят через неё — но политика bookings_cancel_pending осталась на месте,
-- а с ней и прямой путь:
--
--   update bookings set status = 'cancelled', renter_total = 1 ...
--
-- Её `with check` проверяет только renter_id и status, поэтому арендатор
-- мог тем же запросом переписать суммы своей неподтверждённой брони.
-- Функция рядом не мешает: PostgREST открыт, и обращаться напрямую к
-- таблице никто не запрещал. Добавить дверь — не то же самое, что закрыть
-- старую.
--
-- Пока деньги не двигаются, это безвредно. На этапе реальных платежей
-- суммы отменённых броней начнут читаться при возвратах, и цена ошибки
-- станет денежной.
--
-- Теперь у authenticated не остаётся ни одной UPDATE-политики на bookings:
-- все переходы идут через security definer функции. Это ровно тот принцип,
-- который README называет главным — «переходы статусов только через RPC», —
-- и до сих пор он держался на честном слове клиента.
-- ─────────────────────────────────────────────────────────────

drop policy if exists bookings_cancel_pending on bookings;

comment on table bookings is
  'Брони. UPDATE напрямую недоступен никому: все переходы статусов идут '
  'через функции (booking_confirm, booking_cancel, settle_booking и далее). '
  'Политики на update здесь намеренно нет — она позволяла бы переписать '
  'суммы заодно со статусом.';
