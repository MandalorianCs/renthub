-- Модератор видит объявление, по которому идёт спор.
--
-- Политика items_read пускает к активным объявлениям и к своим. Но спор
-- разбирается по фото «до», а они лежат в condition_photos объявления —
-- и владелец мог снять его с публикации сразу после возврата вещи.
--
-- Тогда модератор видел бы претензию с фото «после» и пустотой вместо
-- того, с чем их надо сверять: то есть решал бы вслепую по одной стороне.

create policy items_read_moderator on items
  for select to authenticated
  using (exists (select 1 from users u where u.id = auth.uid() and u.is_moderator));
