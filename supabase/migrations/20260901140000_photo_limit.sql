-- Сколько фото у объявления — правило базы, а не только формы.
--
-- Границы были в трёх местах и ни одного из них не было в базе: форма в
-- приложении не даёт выбрать больше шести, бот считает до шести,
-- create_item() требует хотя бы одно. Но политика items_insert_own
-- разрешает и прямой insert, а он не проходит ни через форму, ни через
-- функцию — знакомая история: дверь добавили, старую не закрыли.
--
-- Последствия разные по обе стороны. Ноль фото — объявление, по которому
-- нельзя разобрать спор: фото «после» не с чем сверять, и это ломает
-- ПРАВИЛО 6 целиком. Двести фото — карточка, которая грузится минуту на
-- телефоне в Кокшетау.
--
-- Верхняя граница шесть — та же, что в форме и в боте. Если её менять,
-- менять придётся в четырёх местах, и это неудобство намеренное: число
-- должно совпадать, а не расходиться незаметно.

-- coalesce обязателен, и это не перестраховка. array_length('{}', 1)
-- возвращает не ноль, а NULL: у пустого массива нет первого измерения. А
-- CHECK отклоняет строку только при false — NULL он пропускает. Без
-- coalesce ограничение молча разрешало бы ровно тот случай, ради которого
-- написано: объявление совсем без фото. Проверено на стенде: вставилось.
alter table items add constraint items_photos_count
  check (
    coalesce(array_length(condition_photos, 1), 0) between 1 and 6
  );

comment on constraint items_photos_count on items is
  'От одного до шести фото. Нижняя граница держит ПРАВИЛО 6: без фото «до» '
  'спор о порче не с чем сверять. Верхняя совпадает с формой и ботом.';
