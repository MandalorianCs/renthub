-- Занятые даты объявления — для того, кто ещё не участник сделки.
--
-- Проблема: политика bookings_read_participants пускает к брони только
-- арендатора и владельца. Это правильно — суммы и личности сторон чужим
-- знать незачем. Но побочный эффект оказался тяжёлым: человек, выбирающий
-- даты, видел ПУСТОЙ календарь занятости, потому что для него запрос к
-- bookings возвращал ноль строк. Он выбирал занятые даты и упирался в
-- ограничение bookings_no_overlap уже после нажатия «Забронировать».
--
-- Решение: отдельная функция, которая отдаёт ровно две колонки — начало
-- и конец занятого периода. Ни арендатора, ни сумм, ни статуса сделки.
-- security definer здесь не дыра, а сужение: функция физически не может
-- вернуть больше, чем перечислено в returns table.

create or replace function item_busy_dates(p_item_id uuid)
returns table (
  start_date date,
  end_date   date
)
language sql
stable
security definer
set search_path = public
as $$
  select b.start_date, b.end_date
    from bookings b
   where b.item_id = p_item_id
     -- Занятыми считаем только живые статусы — ровно те же, что в
     -- ограничении bookings_no_overlap. Если списки разъедутся,
     -- календарь начнёт врать относительно того, что реально запретит база.
     and b.status in ('pending', 'confirmed', 'active')
   order by b.start_date;
$$;

comment on function item_busy_dates(uuid) is
  'Занятые интервалы объявления без раскрытия сторон сделки. Нужна потому, '
  'что RLS на bookings скрывает чужие брони от потенциального арендатора.';
