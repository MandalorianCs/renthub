-- Отменённая бронь не держит депозит.
--
-- Найдено сквозной проверкой продукта 07.09.2026: заявка отменена, на
-- экране статус «Отменено» и рядом плашка «Депозит заблокирован», а строкой
-- ниже — «Даты освободились. Деньги и депозит не удерживаются». Два
-- утверждения на одном экране, и они противоречат друг другу.
--
-- Врал не интерфейс: booking_cancel меняет только status, а deposit_status
-- остаётся 'held'. Плашка честно показывает, что записано в базе.
--
-- Почему триггер, а не правка функций. Отменить бронь можно тремя путями:
-- booking_cancel (приложение), bot_cancel_booking (Telegram) и планировщик,
-- который закрывает неподтверждённые и незабранные. Дописать одну строку в
-- каждую — значит поручить будущему разработчику помнить про все три; тот,
-- кто добавит четвёртый путь, о правиле не узнает.
--
-- Правило «отменённая бронь не держит депозит» — это инвариант данных, а не
-- шаг сценария. Инварианту место рядом с данными.

-- Таймауты перед изменением схемы.
--
-- Требование линтера миграций (npm run check:sql), и требование разумное:
-- create trigger берёт на таблицу исключительную блокировку. Если в этот
-- момент кто-то бронирует, миграция встанет в очередь и остановит вместе с
-- собой всех остальных — деплой превратится в тихую остановку сервиса.
--
-- С lock_timeout она вместо этого упадёт через пять секунд, и мы повторим
-- её через минуту. Упавшая миграция чинится за минуту, зависшая база — нет.
set lock_timeout = '5s';
set statement_timeout = '30s';

create or replace function release_deposit_on_cancel()
returns trigger
language plpgsql
as $$
begin
  -- Только held → released. 'claimed' не трогаем: удержание бывает по
  -- разрешённому спору, а спор возможен лишь после передачи вещи — то
  -- есть в статусе, из которого отмены уже нет. Если такая пара всё же
  -- сложится, значит случилось что-то, чего мы не предусмотрели, и
  -- молча переписывать деньги здесь нельзя.
  if new.deposit_status = 'held' then
    new.deposit_status := 'released';
  end if;

  return new;
end;
$$;

comment on function release_deposit_on_cancel() is
  'Снимает блокировку депозита при переходе брони в cancelled. Инвариант: '
  'отменённая бронь не держит чужие деньги.';

-- before update: значение правится в той же строке, до записи. After
-- потребовал бы второго update и второго прохода триггеров.
create trigger bookings_release_deposit_on_cancel
  before update on bookings
  for each row
  when (new.status = 'cancelled' and old.status is distinct from 'cancelled')
  execute function release_deposit_on_cancel();

-- Разовая починка того, что уже накопилось.
--
-- На пилоте таких броней единицы, но каждая показывает человеку
-- заблокированные деньги, которых никто не держит. Оставить их — значит
-- сохранить противоречие на экране ради чистоты миграции.
update bookings
   set deposit_status = 'released'
 where status = 'cancelled'
   and deposit_status = 'held';
