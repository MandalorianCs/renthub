-- ─────────────────────────────────────────────────────────────
-- my_profile() не должна вызываться анонимом
--
-- В миграции 20260819100000 стояло `revoke all on function ... from public`,
-- и этого оказалось мало: дефолтные привилегии проекта (`alter default
-- privileges in schema public grant all on functions to anon, authenticated,
-- service_role`) выдают право **напрямую роли**, а не через PUBLIC. Отзыв у
-- PUBLIC такое право не снимает.
--
-- Проверено на живом проекте: POST /rest/v1/rpc/my_profile с публичным
-- ключом и без сессии отвечал 200. Утечки не было — auth.uid() у анонима
-- пуст, и функция возвращала строку из одних null, — но security definer
-- функция, доступная анониму, это заряженное ружьё: достаточно однажды
-- добавить в неё аргумент, и она начнёт отдавать чужое.
--
-- Ровно та же ловушка описана в README про колоночные гранты: сначала
-- отзыв поимённо у роли, потом выдача. PUBLIC — не то же самое, что anon.
-- ─────────────────────────────────────────────────────────────

revoke execute on function my_profile() from anon;

comment on function my_profile() is
  'Профиль вызывающего целиком, включая телефон и telegram_id. Единственный '
  'способ прочитать эти колонки из приложения. Анониму вызов запрещён: '
  'выдавать ему security definer функцию незачем даже когда она пуста.';
