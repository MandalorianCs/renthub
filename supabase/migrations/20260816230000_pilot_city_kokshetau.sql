-- Город пилота назван: Кокшетау.
--
-- До этой миграции в дефолте колонки стояло 'almaty' — заглушка, попавшая
-- туда из примера, а не решение. В README он честно числился открытым
-- вопросом. Теперь решён.
--
-- Почему это вообще важно для схемы: каталог фильтруется по city, и если
-- дефолт разойдётся с EXPO_PUBLIC_PILOT_CITY в клиенте, объявления будут
-- создаваться в одном городе, а искаться в другом. Витрина окажется пустой
-- при полной базе — и причину будут искать в запросе, а не в дефолте.

alter table items alter column city set default 'kokshetau';

-- Существующие объявления переносим: на пилоте это тестовые данные, и
-- оставлять их в городе, которого больше нет в настройках, значит просто
-- спрятать их от каталога навсегда.
update items set city = 'kokshetau' where city = 'almaty';

comment on column items.city is
  'Город пилота. Каталог фильтруется по нему; значение обязано совпадать '
  'с EXPO_PUBLIC_PILOT_CITY в клиенте, иначе витрина будет пустой.';
