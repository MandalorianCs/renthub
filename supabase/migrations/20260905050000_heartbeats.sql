-- Отметка «я жив» от бота.
--
-- Зачем. `npm run health` считал доставку по очереди недоставленных
-- уведомлений и поднимал тревогу, когда самому старому больше десяти
-- минут. Это ловит бота, который умер при живом потоке событий.
--
-- И совсем не ловит того, который умер в тишине. Пилот на пять человек —
-- это как раз тишина: сутки без единой брони обычны. Бот лежит, очередь
-- пуста, health говорит «всё хорошо», и узнают об этом на первой же
-- реальной сделке — с задержкой в те самые десять минут, уже после того,
-- как человек не получил подтверждения.
--
-- Отметка переворачивает вопрос. Вместо «есть ли непрощенная работа» —
-- «когда о себе в последний раз напомнил тот, кто эту работу делает».
-- Тишина перестаёт быть неотличимой от смерти.
--
-- Таблица общая, не только для бота: тем же способом отметится любой
-- процесс, который однажды поселится снаружи базы.

create table heartbeats (
  name    text primary key,
  seen_at timestamptz not null default now(),
  note    text
);

comment on table heartbeats is
  'Отметки живости внешних процессов. Пишет тот, кто живёт снаружи базы '
  '(бот); читает scripts/health.mjs. Тишина в очереди задач не отличается '
  'от смерти исполнителя — эта таблица и есть отличие.';

-- RLS включён, политик нет: писать и читать может только служебный ключ.
-- Участнику эта таблица не нужна ни в каком виде, а знание о том, когда
-- бот последний раз просыпался, — лишняя подробность о внутренностях.
alter table heartbeats enable row level security;

-- Первая отметка ставится сразу и заведомо старой: до первого запуска
-- обновлённого бота health честно скажет «не отмечался», а не «строки
-- нет» — второе читается как поломка самой проверки.
insert into heartbeats (name, seen_at, note)
values ('bot', '2000-01-01T00:00:00Z', 'ещё ни разу не отмечался')
on conflict (name) do nothing;
