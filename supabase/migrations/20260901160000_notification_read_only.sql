-- В своём уведомлении человек отмечает прочтение — и только его.
--
-- Политика notifications_mark_read задумана как «отметить прочитанным», но
-- RLS фильтрует СТРОКИ, а не колонки: она пускает к своей строке целиком.
-- Значит из клиента можно переписать title и body, а главное — обнулить
-- sent_at.
--
-- Последнее не косметика. Бот забирает записи с пустым sent_at и шлёт их в
-- Telegram: сброс отметки заставляет доставить уведомление заново. Вреда
-- чужим нет, строка своя, но это способ заставить систему работать вхолостую
-- и получать одно и то же сообщение сколько угодно раз.
--
-- Тот же приём, что с телефоном в users: политика решает, какие СТРОКИ
-- видны и изменяемы, а грант на колонки — какие ПОЛЯ. Порядок обязателен:
-- сначала revoke более широкого права, потом грант поимённо, иначе широкое
-- перекроет узкое.

revoke update on notifications from authenticated;
grant update (read_at) on notifications to authenticated;

comment on policy notifications_mark_read on notifications is
  'Отметить своё уведомление прочитанным. Какие строки — решает политика, '
  'какие поля — грант на колонки: доступен только read_at, иначе из клиента '
  'можно было бы обнулить sent_at и заставить бота слать заново.';
