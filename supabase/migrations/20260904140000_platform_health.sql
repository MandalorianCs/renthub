-- Живое состояние платформы: работает ли то, что обещано словами.
--
-- Два обещания продукта держатся не на коде, а на двух процессах снаружи, и
-- узнать, живы ли они, было нечем.
--
-- **Планировщик.** Лендинг говорит клиенту: «После окончания аренды даётся
-- 12 часов. Дальше система сама открывает спор о невозврате и удерживает
-- депозит», а страница для жюри называет это правилом Trust Score. Держит
-- обещание `process_overdue_bookings()`, который должен запускать pg_cron
-- раз в час. Настраивается это руками в панели Supabase (README, раздел
-- «Регулярная задача»), и никакой отметки о том, сделано ли, нигде нет.
-- Не запущен — правило просто не выполняется, молча.
--
-- **Бот.** Он живёт отдельным процессом и после перезагрузки машины не
-- поднимается сам. Симптом описан в HANDOFF: уведомления копятся в базе с
-- пустым `sent_at` и приходят пачкой при запуске. Заметить это можно было
-- только по тишине в чате.
--
-- ── Почему функция, а не запрос в SQL-редакторе ──────────────
--
-- Запрос уже есть — в `db-tests/90_smoke_live.sql` он лежит закомментирован
-- с 21.08.2026, и его никто не выполнил. Проверка, которую надо вспомнить,
-- открыть панель и вставить, не выполняется никогда; проверка, у которой
-- есть команда, выполняется.
--
-- ── Почему схема cron адресуется динамически ─────────────────
--
-- Пока расширение не включено, схемы `cron` не существует, и Postgres
-- отвергает запрос на разборе — целиком, ещё до выполнения. Тот же разбор
-- и мешал вписать эту проверку в общий смоук. `to_regclass` отвечает NULL
-- вместо ошибки, а сам запрос идёт через `execute`: он разбирается только
-- когда таблица уже есть.

create or replace function platform_health()
returns table (
  part    text,
  state   text,
  alarm   boolean
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_jobs    integer := 0;
  v_unsent  integer;
  v_oldest  interval;
begin
  -- Планировщик.
  if to_regclass('cron.job') is not null then
    execute $q$
      select count(*) from cron.job where command like '%process_overdue_bookings%'
    $q$ into v_jobs;

    part  := 'планировщик';
    state := case
               when v_jobs > 0 then format('задача есть (%s)', v_jobs)
               else 'pg_cron включён, но задачи нет'
             end;
    alarm := v_jobs = 0;
  else
    part  := 'планировщик';
    state := 'pg_cron не включён — просрочки не разбираются';
    alarm := true;
  end if;
  return next;

  -- Бот: недоставленные уведомления и возраст самого старого.
  select count(*), max(now() - created_at)
    into v_unsent, v_oldest
    from notifications
   where sent_at is null;

  part  := 'доставка уведомлений';
  state := case
             when v_unsent = 0 then 'очередь пуста'
             else format('%s в очереди, самому старому %s',
                         v_unsent, date_trunc('minute', v_oldest))
           end;
  -- Тревога не по числу, а по возрасту: очередь наполняется и при живом
  -- боте — между записью и следующим опросом проходит до пятнадцати
  -- секунд. Десять минут означают, что опроса нет.
  alarm := v_oldest > interval '10 minutes';
  return next;

  -- Витрину здесь не считаем намеренно. Признак «демонстрационное»
  -- определяется именем служебного владельца, а имя живёт в
  -- shared/demo-owner.json — одном файле на скрипт и приложение. Вписать
  -- его сюда строкой значило бы завести третью копию ровно того правила,
  -- ради единственности которого файл и заведён. Витрину считает
  -- scripts/health.mjs: он этот файл читает.
end;
$$;

comment on function platform_health() is
  'Живо ли то, что обещано словами: планировщик просрочек и доставка '
  'уведомлений. Оба живут снаружи базы, и до этой функции узнать их '
  'состояние можно было только по тишине.';

-- Только сервисному ключу: это состояние платформы, а не участника.
revoke all on function platform_health() from public;
revoke all on function platform_health() from anon, authenticated;
