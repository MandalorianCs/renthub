-- Каталог без входа.
--
-- До этой миграции неавторизованный человек не видел ничего: политики были
-- выданы только роли authenticated. Для двустороннего маркетплейса это дыра
-- в воронке — «посмотреть, есть ли вообще перфораторы» должно быть возможно
-- до того, как человек введёт номер и будет ждать SMS.
--
-- Тонкость, ради которой эта миграция написана именно так: RLS фильтрует
-- СТРОКИ, а не колонки. Политика «читать всем» на users открыла бы строку
-- целиком, вместе с телефоном. Поэтому здесь два разных механизма:
--   • политика — какие строки видны;
--   • грант на колонки — какие поля этих строк доступны.

-- ── Объявления: видны активные ────────────────────────────────

create policy items_read_anon on items
  for select to anon
  using (status = 'active');

-- ── Справочник категорий ──────────────────────────────────────

create policy categories_read_anon on categories
  for select to anon
  using (true);

-- ── Профили: только витринные поля ────────────────────────────
--
-- Сначала отзываем полный select, который выдали дефолтные привилегии
-- проекта, и возвращаем поимённо. Без revoke грант на колонки бесполезен:
-- более широкое право уже есть и перекрывает его.

revoke select on users from anon;

grant select (id, full_name, rating, ratings_count, created_at) on users to anon;

create policy users_read_anon on users
  for select to anon
  using (true);

comment on policy users_read_anon on users is
  'Аноним видит имя и рейтинг владельца — без этого карточка объявления '
  'бессмысленна. Телефон закрыт грантом на колонки, а не политикой.';
