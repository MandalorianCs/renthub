-- Число закрытых сделок участника — для профиля владельца.
--
-- Профиль существует ради одного решения: отдать ли незнакомцу вещь за
-- 90 000 ₸. До сих пор единственным числом там был счётчик отзывов, а он
-- занижает опыт: отзыв оставляют не после каждой сделки, и человек с
-- двадцатью закрытыми арендами выглядел как человек с тремя.
--
-- Прямым запросом счётчик не достать. Политика bookings_read_participants
-- пускает к брони только её стороны, и для постороннего `select count(*)`
-- вернёт ноль — не «нет сделок», а «вам не видно». Ровно та же ситуация,
-- из которой выросла item_busy_dates(), и решение то же.
--
-- security definer здесь не дыра, а сужение: функция возвращает integer и
-- физически не может отдать ни сторон сделки, ни сумм, ни дат. Наружу
-- уходит одно агрегированное число.

create or replace function user_deals_count(p_user_id uuid)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  -- Считаются обе роли, а не только владение. Человек в пилоте бывает и
  -- тем и другим (users.role_hint по умолчанию 'both'), и счётчик только
  -- по владению давал бы «12 отзывов, 0 сделок» тому, кто пока лишь брал.
  -- Такая пара чисел читается как ошибка, а не как факт.
  select count(*)::int
    from bookings b
    join items i on i.id = b.item_id
   where b.status = 'completed'
     and (b.renter_id = p_user_id or i.owner_id = p_user_id);
$$;

comment on function user_deals_count(uuid) is
  'Сколько сделок участник довёл до completed. Нужна потому, что RLS на '
  'bookings скрывает чужие брони, а витрине нужен агрегат без сторон и сумм.';

-- Витрина открыта без входа, поэтому счётчик нужен и анониму: профиль
-- владельца — публичный экран, на него попадают с карточки объявления
-- до того, как введут номер.
grant execute on function user_deals_count(uuid) to anon, authenticated;
